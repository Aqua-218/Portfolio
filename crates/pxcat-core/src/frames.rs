//! ドット猫のコマ。絵はデザインのモック(pxcats.js)から写した。

use crate::sprite::{Cell, Frame, MAX_H, MAX_W};

/// コマの名前。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FrameName {
    RunA,
    RunB,
    Sleep,
    SitA,
    SitB,
    TailA,
    TailB,
    Peek,
    PeekBlink,
}

/// すべてのコマの名前。
pub const ALL: [FrameName; 9] = [
    FrameName::RunA,
    FrameName::RunB,
    FrameName::Sleep,
    FrameName::SitA,
    FrameName::SitB,
    FrameName::TailA,
    FrameName::TailB,
    FrameName::Peek,
    FrameName::PeekBlink,
];

type Rows = [[u8; MAX_W]; MAX_H];

/// 文字の並びをコマにする。`width`×`height`の外は`Cell::Empty`にする。
const fn build(rows: &Rows, width: usize, height: usize) -> Frame {
    let mut cells = [[Cell::Empty; MAX_W]; MAX_H];
    let mut y = 0;
    while y < height {
        let mut x = 0;
        while x < width {
            cells[y][x] = Cell::from_byte(rows[y][x]);
            x += 1;
        }
        y += 1;
    }
    Frame {
        width,
        height,
        cells,
    }
}

/// 名前からコマを作る。
#[must_use]
pub const fn frame(name: FrameName) -> Frame {
    match name {
        FrameName::RunA => build(&RUN_A, 20, 9),
        FrameName::RunB => build(&RUN_B, 20, 9),
        FrameName::Sleep => build(&SLEEP, 17, 7),
        FrameName::SitA => build(&SIT_A, 14, 12),
        FrameName::SitB => build(&SIT_B, 14, 12),
        FrameName::TailA => build(&TAIL_A, 7, 4),
        FrameName::TailB => build(&TAIL_B, 7, 4),
        FrameName::Peek => build(&PEEK, 7, 6),
        FrameName::PeekBlink => build(&PEEK_BLINK, 7, 6),
    }
}

