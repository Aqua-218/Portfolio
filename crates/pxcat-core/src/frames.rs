use crate::sprite::{Cell, Frame, MAX_H, MAX_W};

/// コマの名前。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FrameName {
    RunA,
    RunB,
    Sleep,
    SitA,
    SitB,
    TailA,
    TailB,
    Peek,
    PeekBlink,
    GroomA,
    GroomB,
    Loaf,
    Stretch,
    RollA,
    RollB,
    PounceA,
    PounceB,
}

