#[test]
fn 輪郭がモックと同じ() {
    for (name, rows) in EXPECTED {
        let out = outline(&frame(name));
        assert_eq!(out.height, rows.len(), "{name:?}");
        for (y, row) in rows.iter().enumerate() {
            assert_eq!(out.width, row.len(), "{name:?}");
            for (x, ch) in row.bytes().enumerate() {
                assert_eq!(out.get(x, y), ch == b'+', "{name:?} ({x}, {y})");
            }
        }
    }
}

#[test]
fn 輪郭は塗りの外側1マス() {
    for name in ALL {
        let f = frame(name);
        let out = outline(&f);
        for y in 0..out.height {
            for x in 0..out.width {
                if !out.get(x, y) {
                    continue;
                }
                // 輪郭のマスは塗られていない
                let inside = x >= 1
                    && y >= 1
                    && !matches!(f.get(x - 1, y - 1), pxcat_core::sprite::Cell::Empty);
                assert!(!inside, "{name:?} ({x}, {y})");
            }
        }
    }
}

#[test]
fn 輪郭は閉じている() {
    // Leanでも証明している(proofs/PxCat/Closed.lean)。ここでは足したコマをすぐ確かめる
    for name in ALL {
        let out = outline(&frame(name));
        let at = |x: usize, y: usize| x < out.width && y < out.height && out.get(x, y);
        for y in 0..out.height {
            for x in 0..out.width {
                if !at(x, y) {
                    continue;
                }
                let near = (0..3).any(|dy| {
                    (0..3).any(|dx| {
                        (dx, dy) != (1, 1)
                            && x + dx >= 1
                            && y + dy >= 1
                            && at(x + dx - 1, y + dy - 1)
                    })
                });
                assert!(near, "{name:?} ({x}, {y}) の輪郭が離れ小島");
            }
        }
    }
}
